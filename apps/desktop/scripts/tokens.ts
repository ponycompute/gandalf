import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export const TOKENS_JSON = fileURLToPath(new URL("../design/tokens.json", import.meta.url));
export const TOKENS_CSS = fileURLToPath(new URL("../src/renderer/tokens.css", import.meta.url));

interface Themed {
  readonly light: string;
  readonly dark: string;
}

interface Token<V> {
  readonly name: string;
  readonly value: V;
}

interface TextStyle {
  readonly name: string;
  readonly fontSize: string;
  readonly lineHeight: string;
  readonly fontWeight: number;
}

interface Tokens {
  readonly colors: readonly Token<Themed | { readonly ref: string }>[];
  readonly shadows: readonly Token<Themed>[];
  readonly families: readonly Token<string>[];
  readonly textStyles: readonly TextStyle[];
  readonly spacing: readonly Token<string>[];
  readonly size: readonly Token<string>[];
  readonly radius: readonly Token<string>[];
  readonly blur: readonly Token<string>[];
}

const SHADCN = {
  background: "content",
  foreground: "label",
  "muted-foreground": "label-secondary",
  primary: "accent-fill",
  "primary-foreground": "on-accent",
  border: "separator",
  input: "field-border",
  ring: "focus-ring",
  destructive: "status-conflict",
} as const;

const NAMESPACES = [
  { group: "spacing", strip: "space-", namespace: "spacing" },
  { group: "size", strip: "", namespace: "spacing" },
  { group: "radius", strip: "radius-", namespace: "radius" },
  { group: "blur", strip: "blur-", namespace: "blur" },
] as const satisfies readonly {
  group: keyof Tokens;
  strip: string;
  namespace: string;
}[];

export function tokensCss(raw: unknown): string {
  const tokens = parseTokens(raw);
  const colorNames = new Set(tokens.colors.map((token) => token.name));
  const themed = [...tokens.colors, ...tokens.shadows].flatMap((token) =>
    "light" in token.value ? [{ name: token.name, value: token.value }] : [],
  );
  const scalars = NAMESPACES.flatMap(({ group, strip, namespace }) =>
    tokens[group].map((token) => ({
      ...token,
      theme: `${namespace}-${unprefix(token.name, strip)}`,
    })),
  );

  const light = [
    ...tokens.colors.map((token) =>
      decl(
        `g-${token.name}`,
        "ref" in token.value ? `var(--g-${known(colorNames, token.value.ref)})` : token.value.light,
      ),
    ),
    ...tokens.shadows.map((token) => decl(`g-${token.name}`, token.value.light)),
    ...tokens.families.map((family) => decl(`g-font-${family.name}`, family.value)),
    ...tokens.textStyles.flatMap((style) => [
      decl(`g-text-${style.name}`, style.fontSize),
      decl(`g-text-${style.name}-line-height`, style.lineHeight),
      decl(`g-text-${style.name}-weight`, String(style.fontWeight)),
    ]),
    ...scalars.map((token) => decl(`g-${token.name}`, token.value)),
  ];
  const dark = themed
    .filter((token) => token.value.dark !== token.value.light)
    .map((token) => decl(`g-${token.name}`, token.value.dark));
  const shadcn = Object.entries(SHADCN).map(([name, token]) =>
    decl(name, `var(--g-${known(colorNames, token)})`),
  );
  const theme = [
    ...Object.keys(SHADCN).map((name) => decl(`color-${name}`, `var(--${name})`)),
    ...tokens.colors.map((token) => decl(`color-${token.name}`, `var(--g-${token.name})`)),
    ...tokens.families.map((family) => decl(`font-${family.name}`, `var(--g-font-${family.name})`)),
    ...tokens.textStyles.flatMap((style) => [
      decl(`text-${style.name}`, `var(--g-text-${style.name})`),
      decl(`text-${style.name}--line-height`, `var(--g-text-${style.name}-line-height)`),
      decl(`text-${style.name}--font-weight`, `var(--g-text-${style.name}-weight)`),
    ]),
    ...scalars.map((token) => decl(token.theme, `var(--g-${token.name})`)),
    ...tokens.shadows.map((token) =>
      decl(`shadow-${unprefix(token.name, "shadow-")}`, `var(--g-${token.name})`),
    ),
  ];

  return [
    "/* Generated by scripts/tokens.ts from design/tokens.json. Do not edit by hand. */",
    "",
    block(":root", light),
    "",
    "@media (prefers-color-scheme: dark) {",
    block(":root", dark, "  "),
    "}",
    "",
    block(":root", shadcn),
    "",
    block("@theme inline", theme),
    "",
  ].join("\n");
}

function decl(name: string, value: string): string {
  return `--${name}: ${value};`;
}

function block(selector: string, lines: readonly string[], indent = ""): string {
  return [
    `${indent}${selector} {`,
    ...lines.map((line) => `${indent}  ${line}`),
    `${indent}}`,
  ].join("\n");
}

function known(names: ReadonlySet<string>, name: string): string {
  if (!names.has(name)) throw new Error(`unknown color token ${name}`);
  return name;
}

function unprefix(name: string, prefix: string): string {
  if (!name.startsWith(prefix)) throw new Error(`token ${name} lacks the prefix ${prefix}`);
  return name.slice(prefix.length);
}

function parseTokens(raw: unknown): Tokens {
  const root = record(raw, "tokens");
  const type = record(root.type, "type");
  return {
    colors: list(record(root.color, "color").tokens, "color.tokens", (item, at) => {
      const token = record(item, at);
      const value = token.value;
      const ref = typeof value === "string" ? /^\{([a-z0-9-]+)\}$/.exec(value)?.[1] : undefined;
      return {
        name: text(token.name, `${at}.name`),
        value: ref === undefined ? themed(value, `${at}.value`) : { ref },
      };
    }),
    shadows: list(record(root.shadow, "shadow").tokens, "shadow.tokens", (item, at) => {
      const token = record(item, at);
      return { name: text(token.name, `${at}.name`), value: themed(token.value, `${at}.value`) };
    }),
    families: Object.entries(record(type.families, "type.families")).map(([name, value]) => ({
      name,
      value: text(value, `type.families.${name}`),
    })),
    textStyles: list(type.groups, "type.groups", (group, at) =>
      list(record(group, at).styles, `${at}.styles`, (item, styleAt) => {
        const style = record(item, styleAt);
        if (typeof style.fontWeight !== "number") throw new Error(`${styleAt}.fontWeight`);
        return {
          name: text(style.name, `${styleAt}.name`),
          fontSize: text(style.fontSize, `${styleAt}.fontSize`),
          lineHeight: text(style.lineHeight, `${styleAt}.lineHeight`),
          fontWeight: style.fontWeight,
        };
      }),
    ).flat(),
    spacing: scalarTokens(root.spacing, "spacing"),
    size: scalarTokens(root.size, "size"),
    radius: scalarTokens(root.radius, "radius"),
    blur: scalarTokens(root.blur, "blur"),
  };
}

function scalarTokens(raw: unknown, at: string): Token<string>[] {
  return list(record(raw, at).tokens, `${at}.tokens`, (item, itemAt) => {
    const token = record(item, itemAt);
    return {
      name: text(token.name, `${itemAt}.name`),
      value: text(token.value, `${itemAt}.value`),
    };
  });
}

function themed(raw: unknown, at: string): Themed {
  const value = record(raw, at);
  return { light: text(value.light, `${at}.light`), dark: text(value.dark, `${at}.dark`) };
}

function record(raw: unknown, at: string): Record<string, unknown> {
  if (typeof raw !== "object" || raw === null || Array.isArray(raw)) {
    throw new Error(`${at} must be an object`);
  }
  return raw as Record<string, unknown>;
}

function list<T>(raw: unknown, at: string, item: (value: unknown, at: string) => T): T[] {
  if (!Array.isArray(raw)) throw new Error(`${at} must be a list`);
  return raw.map((value, index) => item(value, `${at}[${index}]`));
}

function text(raw: unknown, at: string): string {
  if (typeof raw !== "string" || raw === "") throw new Error(`${at} must be a non-empty string`);
  return raw;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(TOKENS_CSS, tokensCss(JSON.parse(readFileSync(TOKENS_JSON, "utf8"))));
}
